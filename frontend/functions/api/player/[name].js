export async function onRequest(context) {
  const nameParam = decodeURIComponent(context.params.name || "").trim().toLowerCase();
  if (!nameParam) {
    return new Response(JSON.stringify({ error: "Missing player name" }), { status: 400 });
  }

  function getRankTier(elo) {
    if (elo === null || elo === undefined) return "Unranked";
    if (elo >= 3100) return "Bedrock";
    if (elo >= 3000) return "Radiant 3";
    if (elo >= 2900) return "Radiant 2";
    if (elo >= 2800) return "Radiant 1";
    if (elo >= 2700) return "Netherite 3";
    if (elo >= 2600) return "Netherite 2";
    if (elo >= 2500) return "Netherite 1";
    if (elo >= 2400) return "Ruby 3";
    if (elo >= 2300) return "Ruby 2";
    if (elo >= 2200) return "Ruby 1";
    if (elo >= 2100) return "Diamond 3";
    if (elo >= 2000) return "Diamond 2";
    if (elo >= 1900) return "Diamond 1";
    if (elo >= 1800) return "Gold 3";
    if (elo >= 1700) return "Gold 2";
    if (elo >= 1600) return "Gold 1";
    if (elo >= 1500) return "Iron 3";
    if (elo >= 1400) return "Iron 2";
    if (elo >= 1300) return "Iron 1";
    if (elo >= 1200) return "Coal 3";
    if (elo >= 1100) return "Coal 2";
    return "Coal 1";
  }

  const found = exactPlayers.find(p => p.name.toLowerCase() === nameParam);
  if (found) {
    const elo = found.elo;
    const profile = {
      uuid: found.uuid,
      name: found.name,
      elo,
      isRanked: found.isRanked,
      tier: found.isRanked ? getRankTier(elo) : "Unranked",
      pts: found.pts || {},
      wins: found.wins || 0,
      losses: found.losses || 0,
      winStreak: found.winStreak || 0,
      bestWinStreak: found.bestWinStreak || 0,
      kills: found.kills || 0,
      deaths: found.deaths || 0,
      winRate: found.winRate || 0,
      kd: found.kd || 0
    };

    return new Response(JSON.stringify(profile), {
      headers: {
        "Content-Type": "application/json",
        "Access-Control-Allow-Origin": "*",
        "Cache-Control": "public, max-age=15"
      }
    });
  }

  return new Response(JSON.stringify({ error: "Player not found" }), {
    status: 404,
    headers: {
      "Content-Type": "application/json",
      "Access-Control-Allow-Origin": "*"
    }
  });
}
